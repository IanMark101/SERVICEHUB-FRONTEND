import { act, renderHook, waitFor } from '@testing-library/react';
import { beforeEach, describe, expect, it, vi } from 'vitest';
import { api } from '../lib/api/axios';
import useProviderMapListings from './useProviderMapListings';
import { responseCache } from '../lib/api/responseCache';
import { socketResources } from '../lib/api/cachePolicy';

vi.mock('../lib/api/axios',()=>({api:{get:vi.fn()}}));
const viewport={center:{latitude:10.3,longitude:123.9},bounds:{north:10.32,south:10.28,east:123.92,west:123.88}};
const filters={search:'  repair  laptop ',category:'Electrical Repair',filter:'rated'};
const pin={id:'outside',title:'Laptop repairs',label:'Public area',area:{latitude:10.4,longitude:123.9,approximate:true}};
const response={data:{success:true,data:{mapPins:[pin],items:[{id:'outside',provider:{name:'John'}}]}}};

describe('provider markers in the location modal',()=>{
  beforeEach(()=>{vi.mocked(api.get).mockReset();});
  it('shows already loaded pins while the viewport or network is still pending', async () => {
    vi.mocked(api.get).mockImplementation(() => new Promise(() => {}));
    const {result,rerender}=renderHook(({view}) => useProviderMapListings(view,filters,[pin]), { initialProps:{ view:null as typeof viewport | null } });
    expect(result.current.pins).toEqual([pin]);
    rerender({ view:viewport });
    expect(result.current.pins).toEqual([pin]);
    await waitFor(() => expect(api.get).toHaveBeenCalled());
    expect(result.current.pins).toEqual([pin]);
  });
  it('queries the map area rather than a selected radius and respects public pin visibility and filters',async()=>{
    vi.mocked(api.get).mockResolvedValue({data:{success:true,data:{...response.data.data,mapPins:[pin,{...pin,id:'exact',area:{...pin.area,approximate:false}}]}}});
    const {result,rerender}=renderHook(({enabled})=>useProviderMapListings(viewport,enabled ? {...filters} : undefined),{initialProps:{enabled:true}});
    await waitFor(()=>expect(result.current.resolved).toBe(true));
    expect(api.get).toHaveBeenCalledWith('/services/nearby',expect.objectContaining({params:expect.objectContaining({radiusKm:30,search:'repair laptop',category:'Electrical Repair',filter:'rated'})}));
    expect(result.current.pins).toEqual([{...pin,providerName:'John'}, {...pin,id:'exact',area:{...pin.area,approximate:false}}]);
    rerender({enabled:true});
    await act(async()=>{await new Promise(resolve=>setTimeout(resolve,300));});
    expect(api.get).toHaveBeenCalledTimes(1);
    rerender({enabled:false});
    expect(result.current.pins).toEqual([]);
  });
  it('deduplicates overlapping viewport requests and includes pins beyond the returned first page',async()=>{
    vi.mocked(api.get).mockResolvedValue({data:{success:true,data:{...response.data.data,items:[],mapPins:[pin]}}});
    const {result}=renderHook(()=>useProviderMapListings({...viewport,bounds:{north:10.8,south:10,east:124.3,west:123.5}},filters));
    await waitFor(()=>expect(result.current.resolved).toBe(true));
    expect(vi.mocked(api.get).mock.calls.length).toBeGreaterThan(1);
    expect(result.current.pins).toEqual([pin]);
  });
  it('ignores a stale request after the viewport changes and retries a failed load',async()=>{
    let finish:((value:typeof response)=>void)|undefined;
    vi.mocked(api.get).mockImplementationOnce(()=>new Promise(resolve=>{finish=resolve;}));
    const {result,rerender}=renderHook(({view})=>useProviderMapListings(view,filters),{initialProps:{view:viewport}});
    await waitFor(()=>expect(api.get).toHaveBeenCalledTimes(1));
    const signal=vi.mocked(api.get).mock.calls[0][1]?.signal;
    vi.mocked(api.get).mockRejectedValueOnce(new Error('Offline'));
    rerender({view:{...viewport,center:{latitude:10.4,longitude:123.9},bounds:{...viewport.bounds,north:10.42,south:10.38}}});
    expect(signal?.aborted).toBe(true);
    await waitFor(()=>expect(result.current.error).toBeTruthy());
    await act(async()=>{finish?.(response);});
    expect(result.current.pins).toEqual([]);
    vi.mocked(api.get).mockResolvedValue(response);
    act(()=>{result.current.retry();});
    await waitFor(()=>expect(result.current.pins).toHaveLength(1));
    expect(result.current.error).toBe('');
  });
  it('keeps known markers through zoom refreshes, empty viewports, failures and retries',async()=>{
    vi.mocked(api.get).mockResolvedValueOnce(response);
    const {result,rerender}=renderHook(({view})=>useProviderMapListings(view,filters),{initialProps:{view:viewport}});
    await waitFor(()=>expect(result.current.resolved).toBe(true));
    const knownPins=result.current.pins;
    let finish:((value:typeof response)=>void)|undefined;
    vi.mocked(api.get).mockImplementationOnce(()=>new Promise(resolve=>{finish=resolve;}));
    rerender({view:{...viewport,bounds:{north:10.315,south:10.29,east:123.915,west:123.89}}});
    // Assert the immediate render as well as the debounced request: neither may clear pins.
    expect(result.current.pins).toBe(knownPins);
    await waitFor(()=>expect(api.get).toHaveBeenCalledTimes(2));
    expect(result.current.loading).toBe(true);
    expect(result.current.pins).toBe(knownPins);
    await act(async()=>{finish?.({data:{success:true,data:{mapPins:[],items:[]}}});});
    await waitFor(()=>expect(result.current.resolved).toBe(true));
    expect(result.current.pins).toBe(knownPins);
    vi.mocked(api.get).mockRejectedValueOnce(new Error('Offline'));
    rerender({view:{...viewport,bounds:{north:10.34,south:10.26,east:123.94,west:123.86}}});
    await waitFor(()=>expect(result.current.error).toBeTruthy());
    expect(result.current.pins).toBe(knownPins);
    vi.mocked(api.get).mockResolvedValue(response);
    act(()=>{result.current.retry();});
    await waitFor(()=>expect(result.current.resolved).toBe(true));
    expect(result.current.pins).toBe(knownPins);
  });
  it('adds newly discovered providers and clears old markers immediately when filters change',async()=>{
    vi.mocked(api.get).mockResolvedValueOnce(response);
    const {result,rerender}=renderHook(({view,criteria})=>useProviderMapListings(view,criteria),{initialProps:{view:viewport,criteria:filters}});
    await waitFor(()=>expect(result.current.resolved).toBe(true));
    const second={...pin,id:'second',title:'Appliance repairs',area:{...pin.area,longitude:124}};
    vi.mocked(api.get).mockResolvedValue({data:{success:true,data:{mapPins:[second],items:[]}}});
    const nextView={...viewport,bounds:{north:10.34,south:10.26,east:124.1,west:123.7}};
    rerender({view:nextView,criteria:filters});
    await waitFor(()=>expect(result.current.pins).toHaveLength(2));
    expect(result.current.pins.map(item=>item.id)).toEqual(['outside','second']);
    vi.mocked(api.get).mockResolvedValue({data:{success:true,data:{mapPins:[],items:[]}}});
    rerender({view:nextView,criteria:{...filters,category:'Plumbing'}});
    expect(result.current.pins).toEqual([]);
    await waitFor(()=>expect(result.current.resolved).toBe(true));
    expect(result.current.pins).toEqual([]);
  });
  it('removes paused and deleted listings on live updates, including pins discovered outside the current viewport',async()=>{
    const second={...pin,id:'second',title:'Still available',area:{...pin.area,latitude:10.41}};
    let available=[pin,second];
    vi.mocked(api.get).mockImplementation(async(_path,options)=>({data:{success:true,data:{mapPins:options?.params.latitude<11 ? available : [],items:[]}}}));
    const {result,rerender}=renderHook(({view})=>useProviderMapListings(view,filters),{initialProps:{view:viewport}});
    await waitFor(()=>expect(result.current.pins).toHaveLength(2));
    rerender({view:{center:{latitude:11.3,longitude:123.9},bounds:{...viewport.bounds,north:11.32,south:11.28}}});
    await waitFor(()=>expect(result.current.resolved).toBe(true));
    expect(result.current.pins).toHaveLength(2);
    available=[second];
    act(()=>responseCache.invalidate(socketResources('SERVICE_LISTING_TOGGLED',{id:pin.id,isAvailable:false}),'socket'));
    await waitFor(()=>expect(result.current.pins.map(item=>item.id)).toEqual(['second']));
    expect(api.get).toHaveBeenCalledWith('/services/nearby',expect.objectContaining({params:expect.objectContaining({latitude:pin.area.latitude,radiusKm:30})}));
    available=[];
    act(()=>responseCache.invalidate(socketResources('SERVICE_LISTING_DELETED',{id:second.id}),'socket'));
    await waitFor(()=>expect(result.current.pins).toEqual([]));
  });
  it('aborts pre-update requests so late responses cannot resurrect a removed listing',async()=>{
    vi.mocked(api.get).mockResolvedValueOnce(response);
    const {result,rerender}=renderHook(({view})=>useProviderMapListings(view,filters),{initialProps:{view:viewport}});
    await waitFor(()=>expect(result.current.pins).toHaveLength(1));
    let finish:((value:typeof response)=>void)|undefined;
    vi.mocked(api.get).mockImplementationOnce(()=>new Promise(resolve=>{finish=resolve;}));
    rerender({view:{...viewport,bounds:{north:10.315,south:10.29,east:123.915,west:123.89}}});
    await waitFor(()=>expect(api.get).toHaveBeenCalledTimes(2));
    const signal=vi.mocked(api.get).mock.calls[1][1]?.signal;
    vi.mocked(api.get).mockResolvedValue({data:{success:true,data:{mapPins:[],items:[]}}});
    act(()=>responseCache.invalidate(['services'],'socket'));
    await waitFor(()=>expect(result.current.pins).toEqual([]));
    expect(signal?.aborted).toBe(true);
    await act(async()=>{finish?.(response);});
    expect(result.current.pins).toEqual([]);
  });
  it('revalidates on reconnect and recovery while retaining markers on a failed refresh',async()=>{
    vi.mocked(api.get).mockResolvedValueOnce(response);
    const {result}=renderHook(()=>useProviderMapListings(viewport,filters));
    await waitFor(()=>expect(result.current.pins).toHaveLength(1));
    const knownPins=result.current.pins;
    vi.mocked(api.get).mockRejectedValueOnce(new Error('Offline'));
    act(()=>responseCache.invalidate(['services'],'reconnect'));
    await waitFor(()=>expect(result.current.error).toBeTruthy());
    expect(result.current.pins).toBe(knownPins);
    vi.mocked(api.get).mockResolvedValue({data:{success:true,data:{mapPins:[],items:[]}}});
    act(()=>window.dispatchEvent(new Event('online')));
    await waitFor(()=>expect(result.current.pins).toEqual([]));
  });
});
